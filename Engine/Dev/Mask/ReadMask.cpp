struct ReadMaskPrivate
{
    KnobPageWPtr page;
    KnobFileWPtr file;
    KnobButtonWPtr reimport;
    KnobButtonWPtr bakeSequence;
    KnobChoiceWPtr fitMode;
    KnobDoubleWPtr customScale;
    KnobDoubleWPtr customOffset;
    KnobBoolWPtr invertY;
    KnobBoolWPtr groupByLayer;
    KnobBoolWPtr autoRebuild;

    bool knobsCreated = false;

    /// Everything the last import created (shapes + layers), for rebuild removal.
    std::list<std::weak_ptr<RotoItem> > importedItems;

    /// Sanitized document shape name (occurrence-disambiguated) -> imported curve.
    /// Used by Bake Sequence to key the per-frame files into the existing shapes.
    std::map<std::string, std::weak_ptr<Bezier> > importedShapes;

    /// The file the current import came from (sequence-resolved): timeline scrubs
    /// only rebuild when a different frame resolves to a different path.
    QString lastImportedPath;

    /// The raw pattern the current import came from: the file knob re-fires on
    /// timeline changes with an UNCHANGED value (see onFileKnobChanged), and a
    /// same-value emission must not re-import.
    QString lastImportedPattern;

    /// While file-driven (import not baked) the shapes are regenerated by the
    /// next import: they are locked against editing. Bake Sequence unlocks.
    bool shapesLocked = false;

    /// True when the current import came from a SEQUENCE pattern (the next
    /// frame's import replaces the shapes). Static imports are editable.
    bool bakeOnImport = false;

    /// Back-pointer to the owning effect (set by the ReadMask constructor).
    ReadMask* self = 0;

    void setImportedShapesLocked(bool locked);

};

