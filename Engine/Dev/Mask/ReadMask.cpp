void
ReadMaskPrivate::setImportedShapesLocked(bool locked)
{
    const RotoContextPtr ctx = self ? (self->getNode() ? self->getNode()->getRotoContext() : RotoContextPtr())
                                    : RotoContextPtr();
    if (!ctx) {
        return;
    }
    for (std::list<std::weak_ptr<RotoItem> >::iterator it = importedItems.begin();
         it != importedItems.end(); ++it) {
        const RotoItemPtr item = it->lock();
        if (!item) {
            continue;
        }
        // Only fire the lock change when the state actually changes: every
        // setLocked emits onItemLockedChanged, which recomputes the settings
        // panel knobs' enabled state from the CURRENT selection - firing it
        // at import time (nothing selected) disabled the Feather/Opacity
        // controls until the user selected a shape.
        if (item->getLocked() == locked) {
            continue;
        }
        item->setLocked(locked, true, RotoItem::eSelectionReasonOther);
    }
    shapesLocked = locked;
}

